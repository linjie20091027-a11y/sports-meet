const fs = require('fs');
const initSqlJs = require('sql.js');
const { Client } = require('pg');
const { backupFile, ensureBackupDir } = require('../database/backupManager');
const { assertCloudDbConfig, buildPgClientConfig } = require('../config/cloudDatabase');

function quoteIdentifier(name) {
  return '"' + String(name || '').replace(/"/g, '""') + '"';
}

function quoteLiteral(value) {
  return "'" + String(value || '').replace(/'/g, "''") + "'";
}

function mapSqliteTypeToPostgres(type) {
  const normalized = String(type || '').trim().toUpperCase();
  if (!normalized) return 'TEXT';
  if (normalized.includes('INT')) return 'INTEGER';
  if (normalized.includes('CHAR') || normalized.includes('CLOB') || normalized.includes('TEXT')) return 'TEXT';
  if (normalized.includes('BLOB')) return 'BYTEA';
  if (normalized.includes('REAL') || normalized.includes('FLOA') || normalized.includes('DOUB')) return 'DOUBLE PRECISION';
  if (normalized.includes('NUMERIC') || normalized.includes('DECIMAL')) return 'NUMERIC';
  if (normalized.includes('BOOL')) return 'BOOLEAN';
  if (normalized.includes('DATE') && !normalized.includes('TIME')) return 'DATE';
  if (normalized.includes('TIME')) return 'TIMESTAMP';
  return 'TEXT';
}

function normalizeSqliteDefaultValue(value) {
  if (value === null || value === undefined) return null;
  const normalized = String(value).trim();
  if (!normalized || /^null$/i.test(normalized)) return null;
  if (/datetime\('now','localtime'\)/i.test(normalized) || /^current_timestamp$/i.test(normalized)) {
    return 'CURRENT_TIMESTAMP';
  }
  return normalized;
}

function buildCreateTableStatement(tableName, columns) {
  const primaryKeys = columns.filter((column) => Number(column.pk) > 0).sort((a, b) => a.pk - b.pk);
  const singleIntegerPrimaryKey = primaryKeys.length === 1
    && primaryKeys[0]
    && mapSqliteTypeToPostgres(primaryKeys[0].type) === 'INTEGER';
  const columnDefs = columns.map((column) => {
    const pgType = mapSqliteTypeToPostgres(column.type);
    const defaultValue = normalizeSqliteDefaultValue(column.dflt_value);
    if (singleIntegerPrimaryKey && primaryKeys[0].name === column.name) {
      return `${quoteIdentifier(column.name)} INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`;
    }
    let definition = `${quoteIdentifier(column.name)} ${pgType}`;
    if (Number(column.notnull)) definition += ' NOT NULL';
    if (defaultValue !== null) definition += ` DEFAULT ${defaultValue}`;
    return definition;
  });
  if (!singleIntegerPrimaryKey && primaryKeys.length > 0) {
    columnDefs.push(`PRIMARY KEY (${primaryKeys.map((column) => quoteIdentifier(column.name)).join(', ')})`);
  }
  return `CREATE TABLE IF NOT EXISTS ${quoteIdentifier(tableName)} (${columnDefs.join(', ')})`;
}

function getSqliteTableNames(sqliteDb) {
  const stmt = sqliteDb.prepare("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name");
  const names = [];
  while (stmt.step()) {
    const row = stmt.getAsObject();
    names.push(row.name);
  }
  stmt.free();
  return names;
}

function getSqliteTableInfo(sqliteDb, tableName) {
  const stmt = sqliteDb.prepare(`PRAGMA table_info(${quoteIdentifier(tableName)})`);
  const columns = [];
  while (stmt.step()) {
    columns.push(stmt.getAsObject());
  }
  stmt.free();
  return columns;
}

function getSqliteUniqueIndexes(sqliteDb, tableName) {
  const listStmt = sqliteDb.prepare(`PRAGMA index_list(${quoteIdentifier(tableName)})`);
  const indexes = [];
  while (listStmt.step()) {
    const indexMeta = listStmt.getAsObject();
    if (!Number(indexMeta.unique)) continue;
    const indexName = String(indexMeta.name || '').trim();
    if (!indexName) continue;
    const infoStmt = sqliteDb.prepare(`PRAGMA index_info(${quoteIdentifier(indexName)})`);
    const columns = [];
    while (infoStmt.step()) {
      const row = infoStmt.getAsObject();
      if (row.name) columns.push(row.name);
    }
    infoStmt.free();
    if (columns.length) indexes.push({ name: indexName, columns });
  }
  listStmt.free();
  return indexes;
}

function getSqliteRows(sqliteDb, tableName) {
  const stmt = sqliteDb.prepare(`SELECT * FROM ${quoteIdentifier(tableName)}`);
  const rows = [];
  while (stmt.step()) {
    rows.push(stmt.getAsObject());
  }
  stmt.free();
  return rows;
}

function buildInsertStatement(tableName, columnNames, rowCount) {
  const values = [];
  for (let rowIndex = 0; rowIndex < rowCount; rowIndex += 1) {
    const placeholders = columnNames.map((_, columnIndex) => `$${rowIndex * columnNames.length + columnIndex + 1}`);
    values.push(`(${placeholders.join(', ')})`);
  }
  return `INSERT INTO ${quoteIdentifier(tableName)} (${columnNames.map(quoteIdentifier).join(', ')}) VALUES ${values.join(', ')}`;
}

function chunkRows(rows, size) {
  const chunks = [];
  for (let index = 0; index < rows.length; index += size) {
    chunks.push(rows.slice(index, index + size));
  }
  return chunks;
}

async function syncIdentitySequence(client, tableName, columns) {
  const primaryKeys = columns.filter((column) => Number(column.pk) > 0);
  if (primaryKeys.length !== 1) return;
  const primaryKey = primaryKeys[0];
  if (mapSqliteTypeToPostgres(primaryKey.type) !== 'INTEGER') return;
  const sequenceQuery = `SELECT pg_get_serial_sequence(${quoteLiteral(tableName)}, ${quoteLiteral(primaryKey.name)}) AS seq`;
  const sequenceRes = await client.query(sequenceQuery);
  const sequenceName = sequenceRes.rows?.[0]?.seq;
  if (!sequenceName) return;
  await client.query(
    `SELECT setval($1, COALESCE((SELECT MAX(${quoteIdentifier(primaryKey.name)}) FROM ${quoteIdentifier(tableName)}), 0) + 1, false)`,
    [sequenceName]
  );
}

async function migrateLocalDbToCloud() {
  const cloudConfig = assertCloudDbConfig();
  ensureBackupDir(cloudConfig.backupDir);
  backupFile(cloudConfig.localDbPath, {
    backupDir: cloudConfig.backupDir,
    prefix: 'pre-cloud-migration',
    extension: 'db',
    maxCount: 10
  });

  if (!fs.existsSync(cloudConfig.localDbPath)) {
    throw new Error('本地数据库不存在: ' + cloudConfig.localDbPath);
  }

  const sql = await initSqlJs();
  const sqliteDb = new sql.Database(fs.readFileSync(cloudConfig.localDbPath));
  const client = new Client(buildPgClientConfig());
  const tableNames = getSqliteTableNames(sqliteDb);
  const summary = [];

  await client.connect();
  try {
    await client.query('BEGIN');
    await client.query(`CREATE SCHEMA IF NOT EXISTS ${quoteIdentifier(cloudConfig.schema)}`);
    await client.query(`SET search_path TO ${quoteIdentifier(cloudConfig.schema)}`);

    for (const tableName of tableNames) {
      const columns = getSqliteTableInfo(sqliteDb, tableName);
      await client.query(buildCreateTableStatement(tableName, columns));
      const uniqueIndexes = getSqliteUniqueIndexes(sqliteDb, tableName);
      for (const index of uniqueIndexes) {
        const safeIndexName = index.name.replace(/[^a-zA-Z0-9_]/g, '_');
        const createIndexSql = `CREATE UNIQUE INDEX IF NOT EXISTS ${quoteIdentifier(safeIndexName)} ON ${quoteIdentifier(tableName)} (${index.columns.map(quoteIdentifier).join(', ')})`;
        await client.query(createIndexSql);
      }
    }

    for (const tableName of tableNames) {
      const columns = getSqliteTableInfo(sqliteDb, tableName);
      const columnNames = columns.map((column) => column.name);
      const rows = getSqliteRows(sqliteDb, tableName);
      await client.query(`TRUNCATE TABLE ${quoteIdentifier(tableName)} RESTART IDENTITY`);
      for (const chunk of chunkRows(rows, 100)) {
        if (!chunk.length) continue;
        const params = [];
        chunk.forEach((row) => {
          columnNames.forEach((columnName) => {
            params.push(row[columnName]);
          });
        });
        await client.query(buildInsertStatement(tableName, columnNames, chunk.length), params);
      }
      await syncIdentitySequence(client, tableName, columns);
      summary.push({ table: tableName, rowCount: rows.length });
    }

    await client.query('COMMIT');
    return {
      cloudConfig,
      summary
    };
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    sqliteDb.close();
    await client.end();
  }
}

async function main() {
  const startedAt = Date.now();
  const result = await migrateLocalDbToCloud();
  console.log('云端数据库迁移完成');
  console.log('目标连接:', result.cloudConfig.maskedUrl);
  result.summary.forEach((item) => {
    console.log(`- ${item.table}: ${item.rowCount} 行`);
  });
  console.log('耗时(ms):', Date.now() - startedAt);
}

if (require.main === module) {
  main().catch((error) => {
    console.error('云端数据库迁移失败:', error.message);
    process.exit(1);
  });
}

module.exports = {
  mapSqliteTypeToPostgres,
  normalizeSqliteDefaultValue,
  buildCreateTableStatement,
  migrateLocalDbToCloud
};
